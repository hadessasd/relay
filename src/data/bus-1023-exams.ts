import type { ExamModule, Mcq, WritingQ } from "./types";

function n(
  id: string,
  tag: string,
  question: string,
  numericAnswer: number,
  explanation: string,
  hint: string,
  hintAr: string,
  extra: Partial<Mcq> = {},
): Mcq {
  return {
    id,
    tag,
    question,
    options: [],
    correctIndex: 0,
    numericAnswer,
    explanation,
    hint,
    hintAr,
    ...extra,
    tolerance: extra.tolerance ?? 0.01,
    frqAnswer: extra.frqAnswer ?? explanation,
  };
}

function choice(
  id: string,
  tag: string,
  question: string,
  options: string[],
  correctIndex: number,
  explanation: string,
  hint: string,
  hintAr: string,
  extra: Partial<Mcq> = {},
): Mcq {
  return { id, tag, question, options, correctIndex, explanation, hint, hintAr, ...extra };
}

function w(
  id: string,
  prompt: string,
  modelAnswer: string,
  hint: string,
  hintAr: string,
  marks: string[],
  chart?: WritingQ["chart"],
): WritingQ {
  return { id, prompt, modelAnswer, hint, hintAr, marks, chart };
}

